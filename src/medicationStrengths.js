export function strengthOptions(medication) {
  const key = medication?.ingredientId ?? medication?.id;
  const forms = byForm[key];
  if (forms) return (medication.category === 'Prescription' ? forms.rx : forms.otc).slice();
  if (strengths[key]) return strengths[key].slice();
  const fromName = String(medication?.name ?? '').match(/\d+(?:\.\d+)?\s*(?:MG|MCG|G|UNT|IU|MEQ|ML)(?:\/\d+(?:\.\d+)?\s*(?:MG|ML|MCG|G))?/gi);
  return fromName ? [...new Set(fromName.map((value) => value.replace(/\s+/g, ' ').toLowerCase().replace(/\bmg\b/, 'mg')))] : [];
}
